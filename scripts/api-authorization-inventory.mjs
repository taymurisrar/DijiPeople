#!/usr/bin/env node
// Route-level authorization inventory (policy API-005).
//
//   node scripts/api-authorization-inventory.mjs            write docs/engineering/api-authorization-inventory.{md,json}
//   node scripts/api-authorization-inventory.mjs --check    fail if the committed inventory is stale
//   node scripts/api-authorization-inventory.mjs --register regenerate api-authorization-register.json (keeps owners/dates of existing entries)
//
// The register is NOT a permanent baseline: every legacy gap carries a priority,
// an owner role and a due date, and the gate fails once a date passes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanApi } from './lib/api-routes.mjs';
import { classifyRoute } from './lib/authz-classify.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MD = path.join(ROOT, 'docs/engineering/api-authorization-inventory.md');
const JSON_OUT = path.join(ROOT, 'docs/engineering/api-authorization-inventory.json');
const REGISTER = path.join(ROOT, 'docs/engineering/api-authorization-register.json');
const DUE_DAYS = { P0: 7, P1: 21, P2: 60, P3: 120 };
const key = (r) => `${r.file}#${r.method} ${r.path}`;

export function buildInventory(root = ROOT) {
  const rows = [];
  for (const c of scanApi(root)) {
    const text = fs.readFileSync(path.join(root, c.file), 'utf8').replace(/\r\n/g, '\n');
    for (const r of c.routes) {
      const cls = classifyRoute({ ...r, file: path.join(root, r.file).replace(/\\/g, '/') && r.file }, text);
      rows.push({ key: key(r), module: r.file.split('/')[4], line: r.line, guards: r.guardNames, ...cls });
    }
  }
  return rows;
}

export const isGap = (row) => !row.declared;

function today() {
  return process.env.GOVERNANCE_TODAY ?? new Date().toISOString().slice(0, 10);
}

function render(rows) {
  const by = {};
  rows.forEach((r) => (by[r.cls] = (by[r.cls] ?? 0) + 1));
  const gaps = rows.filter(isGap);
  const lines = [
    '# API authorization inventory',
    '',
    '> GENERATED by `node scripts/api-authorization-inventory.mjs`. Do not edit.',
    '> Static analysis: handler → injected service method → same-class helpers (depth 2). "Enforced" means an authorization call is *reachable*, not that it is correct. Disprove any row from its evidence.',
    '',
    `Routes: **${rows.length}** · declared contract: **${rows.length - gaps.length}** · without a declared contract: **${gaps.length}**`,
    '',
    '## Classification',
    '',
    '| Class | Routes | Meaning |',
    '|---|---|---|',
    ...Object.entries(by).sort((a, b) => b[1] - a[1]).map(([k, n]) => `| ${k} | ${n} | ${MEANING[k] ?? ''} |`),
    '',
    '## Real gaps first (priority P0 → P1 → P2)',
    '',
    '| Pri | Class | Route | Mutating | Sensitive module | Evidence |',
    '|---|---|---|---|---|---|',
  ];
  const order = { P0: 0, P1: 1, P2: 2, P3: 3 };
  for (const r of gaps.filter((g) => g.priority !== 'P3').sort((a, b) => order[a.priority] - order[b.priority] || a.key.localeCompare(b.key)))
    lines.push(`| ${r.priority} | ${r.cls} | \`${r.key.replace('services/api/src/modules/', '')}\` | ${r.mutating ? 'yes' : 'no'} | ${r.sensitive ? 'yes' : 'no'} | ${r.evidence.join(',') || 'none'}; traced: ${r.traced.join(', ') || 'none'} |`);
  lines.push('', '## Enforced elsewhere (P3: migrate to a declared contract)', '', `${gaps.filter((g) => g.priority === 'P3').length} routes. Per-route evidence is in \`api-authorization-inventory.json\`.`, '');
  return lines.join('\n');
}

const MEANING = {
  PERMISSION_DECLARED: 'tenant/platform permission decorators on the route',
  PUBLIC_DECLARED: '@Public()',
  PLATFORM_ROLE_GUARD: 'PlatformPermissionsGuard + @RequireRoles (platform role contract)',
  MACHINE_OR_TOKEN_GUARD: 'gateway/partner/agent token guard instead of a user session',
  RATE_LIMITED_PUBLIC: 'PublicRateLimitGuard, no session; public by design',
  AUTHENTICATION_ONLY_DECLARED: 'explicit reviewed @AuthenticationOnly()',
  SERVICE_ENFORCED_PLATFORM: 'GAP (low): platform assertion in the service; not declared on the route',
  SERVICE_ENFORCED_PERMISSION: 'GAP (low): permission/scope check in the service; not declared on the route',
  SELF_SCOPED: 'GAP (low): acts only on the caller\'s own records',
  TENANT_SCOPED_NO_ACTION_AUTHZ: 'GAP: any authenticated user of the tenant can reach it',
  NO_AUTHZ_EVIDENCE: 'GAP: authenticated only, no scoping or check found',
};

function main() {
  const argv = process.argv.slice(2);
  const rows = buildInventory();
  if (argv.includes('--register')) {
    const prev = fs.existsSync(REGISTER) ? JSON.parse(fs.readFileSync(REGISTER, 'utf8')) : { entries: [] };
    const old = new Map(prev.entries.map((e) => [e.route, e]));
    const t = new Date(today());
    const entries = rows.filter(isGap).map((r) => {
      const was = old.get(r.key);
      const due = new Date(t.getTime() + DUE_DAYS[r.priority] * 86400000).toISOString().slice(0, 10);
      return { route: r.key, class: r.cls, priority: r.priority, ownerRole: r.sensitive || r.priority === 'P0' || r.priority === 'P1' ? 'dp-security-reviewer' : `module-owner:${r.module}`, status: was?.status ?? 'OPEN', due: was?.due ?? due };
    }).sort((a, b) => a.priority.localeCompare(b.priority) || a.route.localeCompare(b.route));
    fs.writeFileSync(REGISTER, JSON.stringify({ doc: 'Legacy routes without a declared authorization contract. NOT a permanent baseline: each has a priority, owner role and due date; the gate (API-005) fails when a date passes, when a route is missing from here, or when an entry no longer matches a route. Remove an entry by declaring a contract on the route.', generated: today(), entries }, null, 2) + '\n');
    console.log(`register: ${entries.length} entries`);
    return;
  }
  const md = render(rows);
  const json = JSON.stringify(rows.map(({ key: k, ...r }) => ({ route: k, ...r })), null, 1) + '\n';
  if (argv.includes('--check')) {
    const stale = [[MD, md], [JSON_OUT, json]].filter(([f, c]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n') !== c);
    if (stale.length) { console.error('authorization inventory is stale — run node scripts/api-authorization-inventory.mjs'); process.exit(1); }
    console.log('authorization inventory current');
    return;
  }
  fs.writeFileSync(MD, md);
  fs.writeFileSync(JSON_OUT, json);
  const by = {};
  rows.forEach((r) => (by[r.cls] = (by[r.cls] ?? 0) + 1));
  console.log(by);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
