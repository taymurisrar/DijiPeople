#!/usr/bin/env node
/*
 * Give sessions, QA runs and engineering-history records the edges they already
 * have, so the vault graph stops showing them as loose dots.
 *
 * These three categories are exempted from the orphan check in
 * `sync-obsidian.mjs` under STANDALONE_CATEGORIES, and two of the stated reasons
 * assert a link that does not exist:
 *
 *   'a history record narrates one task end to end and is reached from that task'
 *   'a QA run is dated execution evidence; the scenarios it ran carry the relationships'
 *
 * Neither is true as written. A history record names its bugs as plain text —
 * `BUG-1543, 1548, 1551` — and a QA run names its scenarios the same way, so
 * nothing points either way and the note is unreachable in the graph. The
 * exemption was hiding that, which is why `OBSIDIAN_GRAPH_ORPHANS` reported 0
 * while 182 notes floated free.
 *
 * This is NOT "add a link to remove a dot", which the verifier rightly forbids.
 * Every edge emitted here is a record id the note already cites in its own prose;
 * the block only makes the citation navigable. Ids that resolve to no note are
 * dropped rather than emitted as dead links.
 *
 *   node scripts/generate-record-graph.mjs [--check]
 */

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, resolve, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEFAULT_MAPPINGS } from './lib/obsidian-mappings.mjs';
/* Line endings are a property of the checkout, not the content — BUG-1208. */
import { indexIsCurrent } from './lib/index-drift.mjs';
/* Shared with rebuild-backlog.mjs so both resolve a module the same way. */
import { moduleNoteNames, resolveModuleNote } from './lib/module-notes.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const OPEN = '<!-- GRAPH:BEGIN — generated by scripts/generate-record-graph.mjs -->';
const CLOSE = '<!-- GRAPH:END -->';

/** The categories this owns, and what each one's edges mean. */
const CATEGORIES = [
  {
    dir: 'docs/sessions',
    label: 'session',
    lead: 'Records this session worked on, cited in its own body:',
  },
  {
    dir: 'docs/qa/runs',
    label: 'QA run',
    lead: 'Scenarios and records this run exercised, cited in its own body:',
  },
  {
    dir: 'docs/engineering-history/tasks',
    label: 'history',
    lead: 'Records this task created, closed or depended on, cited in its own body:',
  },
];

/*
 * `REG-nnn` is deliberately absent.
 *
 * The regression register is ONE file with a row per regression, not a note per
 * id, so `[[REG-201]]` can never resolve. `validate-framework.mjs` scores that
 * as an error rather than a warning for exactly this reason.
 */
const RECORD_ID =
  /\b(BUG-\d{4}|ITEM-\d{4}|TASK-\d{4}|SESSION-\d{4}|QUESTION-\d{4}|ADR-\d{4}|QA-[A-Z]+-\d{3}|EXECPLAN-\d{4}|PLAN-\d{3})\b/g;

/** Files a folder publishes, excluding the generated listing surfaces. */
const LISTINGS = new Set([
  'index',
  'README',
  'active',
  'completed',
  'open',
  'blocked',
  'deferred',
  'product-decisions',
  'coverage-matrix',
]);

function markdownIn(dir, found = []) {
  const path = join(ROOT, dir);
  if (!existsSync(path)) return found;
  for (const entry of readdirSync(path)) {
    const full = join(path, entry);
    if (statSync(full).isDirectory()) markdownIn(join(dir, entry), found);
    else if (entry.endsWith('.md') && !LISTINGS.has(basename(entry, '.md'))) found.push(full);
  }
  return found;
}

/*
 * Every name a wikilink could resolve to: the note's basename, plus each of its
 * frontmatter aliases. Built across every mapped folder, because a session may
 * legitimately cite a bug, a task, a scenario or a plan.
 *
 * Emitting a link to something outside this set would produce a dead wikilink,
 * which renders as ordinary text and announces nothing — the failure mode this
 * whole exercise is meant to remove, not add to.
 */
function resolvableNames() {
  const names = new Set();
  for (const mapping of DEFAULT_MAPPINGS) {
    for (const file of markdownIn(mapping.from)) {
      names.add(basename(file, '.md'));
      const body = readFileSync(file, 'utf8').slice(0, 2048);
      const aliases = /^aliases:\s*\[([^\]]*)\]\s*$/m.exec(body);
      if (!aliases) continue;
      for (const alias of aliases[1].split(',')) {
        const trimmed = alias.trim().replace(/^["']|["']$/g, '');
        if (trimmed) names.add(trimmed);
      }
    }
  }
  return names;
}

/** The record this note IS, so it does not link to itself. */
function selfIds(body) {
  const ids = new Set();
  const explicit = /^(?:SESSION_ID|ID|TASK_ID|BUG_ID|ITEM_ID|QUESTION_ID):\s*(\S+)\s*$/gm;
  for (const match of body.matchAll(explicit)) ids.add(match[1]);
  const aliases = /^aliases:\s*\[([^\]]*)\]\s*$/m.exec(body.slice(0, 2048));
  if (aliases) {
    for (const alias of aliases[1].split(',')) {
      const trimmed = alias.trim().replace(/^["']|["']$/g, '');
      if (trimmed) ids.add(trimmed);
    }
  }
  return ids;
}

/*
 * A session that cites no record still declares `AFFECTED_MODULES`, and that is
 * a real relationship — it is the same field `rebuild-backlog.mjs` turns into
 * edges on a bug record. Without it, 33 sessions stay isolated for no better
 * reason than that their work was described by area rather than by record id.
 */
function declaredModules(body, moduleNames) {
  const declared = /^AFFECTED_MODULES:\s*\[([^\]]*)\]\s*$/m.exec(body.slice(0, 2048));
  if (!declared) return [];
  return [
    ...new Set(
      declared[1]
        .split(',')
        .map((entry) => resolveModuleNote(entry, moduleNames))
        .filter(Boolean),
    ),
  ].sort();
}

/*
 * Branch → the engineering-history note that narrates it.
 *
 * The STANDALONE_CATEGORIES exemption claims a history record "is reached from
 * that task". Nothing actually pointed at one, so the claim was aspirational.
 * A session and its history record name the same `agent/*` branch, and that is
 * the edge that makes the claim true — in the direction that exists.
 */
function historyByBranch() {
  const byBranch = new Map();
  for (const file of markdownIn('docs/engineering-history/tasks')) {
    const body = readFileSync(file, 'utf8');
    const branch = /\|\s*\*\*Task Branch\*\*\s*\|\s*`([^`]+)`/.exec(body);
    if (!branch) continue;
    /* First writer wins: a branch reused across tasks keeps its earliest record. */
    if (!byBranch.has(branch[1])) byBranch.set(branch[1], basename(file, '.md'));
  }
  return byBranch;
}

const names = resolvableNames();
const moduleNames = moduleNoteNames(ROOT);
const historyForBranch = historyByBranch();
const problems = [];
const changed = [];
let totalEdges = 0;
let linked = 0;
let bare = 0;

for (const category of CATEGORIES) {
  for (const file of markdownIn(category.dir)) {
    const original = readFileSync(file, 'utf8');

    /* Read ids from the note as authored, never from a block written earlier. */
    const start = original.indexOf(OPEN);
    const authored = start === -1 ? original : original.slice(0, start);

    /*
     * Bookkeeping keys are not citations.
     *
     * `STANDALONE_ALLOWED_BY: SESSION-0081` records who signed an exemption. Read
     * as prose it looks like a citation, and one pass duly gave five unrelated
     * sessions an edge to whichever session happened to sign their exemption —
     * an edge that says nothing about the work either did.
     */
    const prose = authored.replace(/^(?:STANDALONE_ALLOWED_BY|OwnerAgent|UpdatedBy):.*$/gm, '');

    const self = selfIds(authored);
    const cited = [...new Set([...prose.matchAll(RECORD_ID)].map((m) => m[1]))]
      .filter((id) => !self.has(id) && names.has(id))
      .sort();

    const modules = declaredModules(authored, moduleNames);

    /* A session's own branch, narrated end to end by one history record. */
    const branch = /^TASK_BRANCH:\s*(\S+)\s*$/m.exec(authored.slice(0, 2048));
    const history =
      category.dir === 'docs/sessions' && branch ? (historyForBranch.get(branch[1]) ?? null) : null;

    let next;
    if (cited.length === 0 && modules.length === 0 && !history) {
      bare += 1;
      /* Nothing to declare. Strip a stale block rather than leave one behind. */
      next = start === -1 ? original : `${original.slice(0, start).trimEnd()}\n`;
    } else {
      linked += 1;
      totalEdges += cited.length + modules.length + (history ? 1 : 0);
      const lines = [OPEN, '', '## Related', ''];
      if (history) {
        lines.push(
          `Engineering history for \`${branch[1]}\`:`,
          '',
          `[[${history}]]`,
          '',
        );
      }
      if (cited.length > 0) {
        lines.push(category.lead, '', cited.map((id) => `[[${id}]]`).join(' · '), '');
      }
      if (modules.length > 0) {
        lines.push(
          'Modules this record declares as affected:',
          '',
          modules.map((note) => `[[${note}]]`).join(' · '),
          '',
        );
      }
      lines.push(CLOSE, '');
      next = `${authored.trimEnd()}\n\n${lines.join('\n')}`;
    }

    if (indexIsCurrent(original, next)) continue;
    if (CHECK) problems.push(`${category.dir}/${basename(file)}: Related block is stale`);
    else {
      writeFileSync(file, next);
      changed.push(basename(file));
    }
  }
}

console.log(
  `record-graph: ${linked} note(s) linked, ${totalEdges} edge(s), ` +
    `${bare} note(s) cite no resolvable record`,
);
if (changed.length > 0) console.log(`updated: ${changed.length} file(s)`);

if (problems.length > 0) {
  console.error('\nPROBLEMS');
  for (const problem of problems.slice(0, 20)) console.error(`  - ${problem}`);
  if (problems.length > 20) console.error(`  … and ${problems.length - 20} more`);
  console.error('\nRun `node scripts/generate-record-graph.mjs` and commit the result.');
  process.exit(1);
}

console.log(CHECK ? 'RECORD_GRAPH: CURRENT' : 'RECORD_GRAPH: WRITTEN');
