#!/usr/bin/env node
/*
 * Validate question records and regenerate their indexes.
 *
 *   node scripts/rebuild-questions.mjs           # rewrite indexes
 *   node scripts/rebuild-questions.mjs --check   # fail on drift, write nothing
 *   node scripts/rebuild-questions.mjs --json
 *   node scripts/rebuild-questions.mjs --root <dir>
 *
 * The indexes are generated, never hand-maintained — the same rule the backlog,
 * task, session and QA trees already follow.
 *
 * `open.md` is the one a human actually reads: it is the list of things the
 * framework is waiting on an answer for. If it is empty, nothing is stalled on
 * the user, and any package sitting in WAITING_USER is stalled on nothing —
 * which `check-work-packages.mjs` reports from the other side.
 *
 * Exit codes: 0 valid · 1 invalid or stale · 2 usage error
 *
 * No dependencies.
 */

import { existsSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { loadQuestions, QUESTION_DIR, writeIfChanged } from './lib/question-records.mjs';

const DEFAULT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const argv = process.argv.slice(2);

function option(name, fallback = '') {
  const index = argv.indexOf(`--${name}`);
  return index === -1 ? fallback : (argv[index + 1] ?? '');
}

if (argv.includes('--help')) {
  console.error('Usage: node scripts/rebuild-questions.mjs [--check] [--json] [--root <dir>]');
  process.exit(2);
}

const ROOT = option('root') ? resolve(option('root')) : DEFAULT_ROOT;
const checkOnly = argv.includes('--check');
const wantJson = argv.includes('--json');

const dir = join(ROOT, QUESTION_DIR);
if (!existsSync(dir)) {
  if (checkOnly) {
    console.log('No docs/questions/ tree — nothing to validate.');
    process.exit(0);
  }
  mkdirSync(dir, { recursive: true });
}

const { questions, errors } = loadQuestions(ROOT);

const open = questions.filter((entry) => entry.status === 'OPEN');
const answered = questions.filter((entry) => entry.status === 'ANSWERED');

const row = (entry) =>
  `| [${entry.id}](${entry.relative.split('/').pop()}) | ${entry.title} | ${entry.category} | ` +
  `${entry.askedBy} | ${entry.blocking} | ${entry.taskId || '—'} ${entry.workPackageId || ''} | ` +
  `${entry.decisionId || '—'} |`;

const table = (entries, emptyLine) =>
  entries.length
    ? [
        '| ID | QUESTION | CATEGORY | ASKED BY | BLOCKING | SCOPE | DECISION |',
        '|---|---|---|---|---|---|---|',
        ...entries.map(row),
      ].join('\n')
    : emptyLine;

const generatedNote =
  '<!-- Generated by scripts/rebuild-questions.mjs. Do not edit by hand. -->';

const indexBody = `# Questions

${generatedNote}

A question is here because repository evidence could not answer it. Anything an
agent can establish by reading this repository is an assumption to verify, not a
question to ask.

Answered questions in the durable categories carry an ADR, so the decision is
retrievable by a later task and the user is not asked again.

- **Open — waiting on an answer:** ${open.length}
- **Answered:** ${answered.length}
- **Total:** ${questions.length}

## Open

${table(open, 'Nothing is waiting on a user answer.')}

## Answered

${table(answered, 'No questions have been answered yet.')}
`;

const openBody = `# Open questions

${generatedNote}

${open.length} question(s) waiting on an answer.

${table(open, 'Nothing is waiting on a user answer.')}
`;

let changed = 0;
if (!checkOnly) {
  if (writeIfChanged(join(dir, 'index.md'), indexBody)) changed += 1;
  if (writeIfChanged(join(dir, 'open.md'), openBody)) changed += 1;
}

const stale = [];
if (checkOnly) {
  /*
   * Compared rather than written. `--check` must be side-effect free: a check
   * that repairs what it is checking always passes, which makes it worthless in
   * CI. Line endings are normalised because this repository is worked on from
   * Windows checkouts where Git rewrites them on the way out.
   */
  const compare = (name, body) => {
    const path = join(dir, name);
    if (!existsSync(path)) {
      stale.push(name);
      return;
    }
    const onDisk = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
    if (onDisk !== body.replace(/\r\n/g, '\n')) stale.push(name);
  };
  compare('index.md', indexBody);
  compare('open.md', openBody);
}

if (wantJson) {
  console.log(
    JSON.stringify(
      {
        ok: errors.length === 0 && stale.length === 0,
        errors,
        stale,
        open: open.map((entry) => entry.id),
        answered: answered.map((entry) => entry.id),
        total: questions.length,
      },
      null,
      2,
    ),
  );
  process.exit(errors.length === 0 && stale.length === 0 ? 0 : 1);
}

if (errors.length) {
  console.error(`Question records INVALID — ${errors.length} problem(s):`);
  for (const error of errors) console.error(`  x ${error}`);
  process.exit(1);
}

if (stale.length) {
  console.error(`Question indexes are stale — run \`node scripts/rebuild-questions.mjs\`:`);
  for (const name of stale) console.error(`  x ${name}`);
  process.exit(1);
}

if (checkOnly) {
  console.log(`Question records valid and indexes current — ${questions.length} record(s), ${open.length} open.`);
} else {
  console.log(`Questions rebuilt — ${questions.length} record(s), ${open.length} open, ${changed} index(es) rewritten.`);
}
