import { chromium } from '@playwright/test';
import { readFileSync } from 'node:fs';
const env = Object.fromEntries(readFileSync(new URL('../../../.env.qa.local', import.meta.url), 'utf8').split(/\r?\n/).filter((l) => l && !l.startsWith('#')).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]));
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await p.goto(env.QA_WEB_URL + '/login');
await p.waitForLoadState('networkidle').catch(() => {});
await p.getByLabel(/email/i).first().fill(env.QA_PAYROLL_EMAIL);
await p.getByLabel(/password/i).first().fill(env.QA_PASSWORD);
await p.getByRole('button', { name: /sign in|log in/i }).first().click();
await p.waitForURL((u) => !/login/.test(u.pathname));
await p.getByRole('button', { name: /demo/i }).first().click();
await p.waitForTimeout(500);
const loc = p.getByText('Logout', { exact: true });
console.log('matches', await loc.count());
await loc.first().click();
await p.waitForTimeout(3000);
console.log('url', p.url());
await p.screenshot({ path: 'D:/My Work/hrm-dijipeople/dijipeople-starter-qa/e2e/golive-results/explore/logout.png' });
console.log(await p.evaluate(() => document.body.innerText.slice(0, 300)));
await b.close();
