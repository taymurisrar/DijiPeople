// Turns golive-results/results.json into an immutable run report under docs/qa/go-live/runs/
// and appends it to the dashboard in README.md's run index (runs/INDEX.md).
// Usage: node e2e/golive/tools/make-run-report.mjs [--note "text"]
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../../../', import.meta.url));
// Merge every per-project result file (results-<project>.json); fall back to results.json for a single run.
import { readdirSync as _ls } from 'node:fs';
// RUN-006: `--dir <path>` reads the MERGED per-project result files of one run (relative to the repository root); the default keeps the earlier behaviour.
const dirArg = process.argv.includes('--dir') ? process.argv[process.argv.indexOf('--dir') + 1] : '';
const resDir = dirArg ? join(root, dirArg) : join(root, 'e2e/golive-results');
const files = _ls(resDir).filter((f) => /^results-.+.json$/.test(f));
const parts = (files.length ? files : ['results.json']).map((f) => JSON.parse(readFileSync(join(resDir, f), 'utf8')));
const results = { suites: parts.flatMap((p) => p.suites), stats: { duration: parts.reduce((a, p) => a + (p.stats?.duration ?? 0), 0) }, config: parts[0].config };
const runsDir = join(root, 'docs/qa/go-live/runs');
mkdirSync(runsDir, { recursive: true });
const note = process.argv.includes('--note') ? process.argv[process.argv.indexOf('--note') + 1] : '';

const existing = readdirSync(runsDir).filter((f) => /^RUN-\d+/.test(f));
const n = String(existing.length + 1).padStart(3, '0');
const date = new Date().toISOString().slice(0, 16).replace('T', ' ');
const commit = execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim();

const rows = [];
const walk = (suite) => {
  for (const spec of suite.specs ?? [])
    for (const t of spec.tests)
      for (const r of t.results.slice(-1)) {
        const id = (spec.title.match(/\[(DPQA-[A-Z0-9-]+)\]/) ?? [])[1] ?? spec.title.slice(0, 30);
        rows.push({ id, project: t.projectName, status: t.status === 'expected' ? 'PASS' : t.status === 'skipped' ? 'SKIP' : 'FAIL', ms: r.duration, title: spec.title.replace(/\[DPQA-[A-Z0-9-]+\]\s*/, '') });
      }
  for (const s of suite.suites ?? []) walk(s);
};
results.suites.forEach(walk);
const tally = (p) => rows.filter((r) => r.status === p).length;
const bySuite = {};
for (const r of rows) {
  const k = r.id.split('-')[1] ?? '?';
  (bySuite[k] ??= { PASS: 0, FAIL: 0, SKIP: 0 })[r.status]++;
}

const md = `# RUN-${n} — ${date}

> Immutable. Generated by \`make-run-report.mjs\` from \`golive-results/results.json\`. ${note}

- **Commit:** \`${commit}\` · **Plan:** Starter (ENFORCE) · **Tenant:** qa-starter · **Env:** local, isolated DB
- **Totals:** ${rows.length} executed — **${tally('PASS')} passed**, **${tally('FAIL')} failed**, ${tally('SKIP')} skipped
- **Playwright:** ${results.config?.version ?? ''} · duration ${(results.stats?.duration / 1000 / 60).toFixed(1)} min
- **Automated vs manual:** all rows below automated; manual/MCP checks are listed in the issue records.

| Suite | Pass | Fail | Skip |
|---|---|---|---|
${Object.entries(bySuite).map(([k, v]) => `| ${k} | ${v.PASS} | ${v.FAIL} | ${v.SKIP} |`).join('\n')}

## Results

| Test ID | Project | Result | ms | Title |
|---|---|---|---|---|
${rows.map((r) => `| ${r.id} | ${r.project} | ${r.status} | ${r.ms} | ${r.title} |`).join('\n')}
`;
const file = `RUN-${n}-${date.slice(0, 10)}.md`;
writeFileSync(join(runsDir, file), md);

const idx = join(runsDir, 'INDEX.md');
const head = '# QA run index\n\n| Run | Date | Commit | Executed | Pass | Fail | Skip |\n|---|---|---|---|---|---|---|\n';
const prev = existsSync(idx) ? readFileSync(idx, 'utf8') : head;
writeFileSync(idx, `${prev.trimEnd()}\n| [[${file.replace('.md', '')}]] | ${date} | \`${commit}\` | ${rows.length} | ${tally('PASS')} | ${tally('FAIL')} | ${tally('SKIP')} |\n`);
console.log('wrote', file);
