// Per-run retest matrix: for every DP-QA-001..034, the mapped tests and their result per browser project in the MERGED run results.
// Usage (from e2e/): node golive/tools/retest-matrix.mjs <mergedDir> <out.md>   - evidence, not a verdict: statuses only.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { MAP } from './traceability-map.mjs';
const [dir, out] = process.argv.slice(2);
const res = {}; // id -> project -> status
const walk = (ss, f) => { for (const s of ss ?? []) { for (const sp of s.specs ?? []) for (const t of sp.tests) f(sp, t); walk(s.suites, f); } };
for (const f of readdirSync(dir).filter((x) => /^results-.+\.json$/.test(x))) {
  walk(JSON.parse(readFileSync(`${dir}/${f}`, 'utf8')).suites, (sp, t) => {
    const m = sp.title.match(/\[DPQA-([A-Z0-9-]+)\]/); if (!m) return;
    const r = t.results.at(-1); const st = !r ? 'notrun' : r.status === 'passed' ? 'pass' : r.status === 'skipped' ? 'skip' : 'FAIL';
    (res[m[1]] ??= {})[t.projectName] = st;
  });
}
const cell = (id) => { const p = res[id]; if (!p) return `${id}: _not in run_`; const e = Object.entries(p).filter(([k]) => k !== 'setup'); return `${id}: ` + e.map(([k, v]) => `${k} ${v}`).join(', '); };
const rows = Object.entries(MAP).map(([d, e]) => `| [[${d}]] | ${Array.isArray(e) ? e.map(cell).join('<br>') : `_manual:_ ${e.manual}`} |`);
writeFileSync(out, `# RUN-005 retest evidence by defect\n\nGenerated by \`retest-matrix.mjs\` from the merged RUN-005 results. Statuses only - the verdict per defect is in [[KNOWN-ISSUES]] and the run report.\n\n| Defect | Mapped tests - result per project |\n|---|---|\n${rows.join('\n')}\n`);
console.log('wrote', out);
