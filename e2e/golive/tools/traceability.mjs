const raw = execSync('npx playwright test -c playwright.golive.config.ts --list --reporter=json', { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });
const j = JSON.parse(raw);
const ids = new Set(); const noId = []; const walk = (ss) => { for (const s of ss ?? []) { for (const sp of s.specs ?? []) { const m = sp.title.match(/\[DPQA-([A-Z0-9-]+)\]/); m ? ids.add(m[1]) : noId.push(sp.title); } walk(s.suites); } };
walk(j.suites);
const problems = [];
if ((j.errors ?? []).length) problems.push(`load errors: ${j.errors.length}`);
for (const t of noId) problems.push(`test without a stable id: ${t}`);
for (let n = 1; n <= 34; n++) {
  const d = `DP-QA-${String(n).padStart(3, '0')}`; const e = MAP[d];
  if (!e) { problems.push(`${d}: no mapping`); continue; }
  if (Array.isArray(e)) for (const t of e) if (!ids.has(t)) problems.push(`${d}: test ${t} does not exist`);
}
const rows = Object.entries(MAP).map(([d, e]) => `| [[${d}]] | ${Array.isArray(e) ? e.map((t) => `\`${t}\``).join(', ') : `_manual / unsupported:_ ${e.manual}`} |`);
const md = `# Defect traceability\n\nGenerated by \`e2e/golive/tools/traceability.mjs --write\` from the real test list (${ids.size} unique test ids). Do not hand-edit.\nA mapped id that does not exist, a test without an id, or an unmapped defect fails the generator.\n\n| Defect | Automated tests |\n|---|---|\n${rows.join('\n')}\n`;
if (process.argv.includes('--write')) writeFileSync('../docs/qa/go-live/TRACEABILITY.md', md);
console.log(`unique ids: ${ids.size}; problems: ${problems.length}`); problems.forEach((p) => console.log(' - ' + p));
process.exit(problems.length ? 1 : 0);
